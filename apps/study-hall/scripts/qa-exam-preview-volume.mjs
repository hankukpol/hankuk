// Presentation-only stress fixture delivered to an isolated browser. No persisted data writes.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const info=JSON.parse(fs.readFileSync('.local/exam-preview/runtime.json','utf8'));
assert.ok(info.fixtureOnly&&new URL(info.baseUrl).hostname==='127.0.0.1');
const fixture=JSON.parse(fs.readFileSync(path.join(info.mockDir,'manifest.json'),'utf8'))[0];
const evidence=path.resolve('.superloopy/evidence/frontend/2026-09-16-exam-preview-paging');
fs.mkdirSync(evidence,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({baseURL:info.baseUrl,viewport:{width:1280,height:960}});
context.setDefaultTimeout(60000);
const errors=[];
try {
 assert.equal((await context.request.post('/api/auth/login',{data:{email:fixture.adminEmail,password:'local-preview'}})).status(),200);
 const query=new URLSearchParams({examTypeId:fixture.morningTypeId,studentId:fixture.studentId,from:fixture.from,to:fixture.to});
 const response=await context.request.get(`/api/police/exam-analysis-preview/morning?${query}`);assert.equal(response.status(),200);
 const data=await response.json(),subject=data.subjects[0],sampleRow=data.comparisons.find(r=>r.subjectId===subject.id),sampleItem=data.items.find(i=>i.subjectId===subject.id);
 data.range={from:'2026-08-01',to:'2026-08-24'};
 const dates=Array.from({length:24},(_,i)=>`2026-08-${String(i+1).padStart(2,'0')}`);
 data.comparisons=data.comparisons.filter(r=>r.subjectId!==subject.id);
 data.items=[];data.records=[];
 dates.forEach((date,index)=>{
  const sessionId=`volume-${index}`;
  data.comparisons.push({...sampleRow,sessionId,date,fullScore:125,my:100,topic:'브라우저 검증용 시험 범위'});
  for(let n=1;n<=25;n++)data.items.push({...sampleItem,id:`${sessionId}-${n}`,sessionId,date,itemNo:n,points:5,correct:n<=20,answer:n<=20?sampleItem.answerKey:'검증 오답',externalRate:80});
  data.records.push({id:sessionId,date,subject:subject.name,score:100,fullScore:125,source:'브라우저 검증용 합성 성적'});
 });
 const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/api/police/exam-analysis-preview/morning?*',route=>route.fulfill({json:data}));
 await page.goto(`/police/admin/exams/preview/students/${fixture.studentId}?kind=morning&${query}`,{waitUntil:'domcontentloaded'});
 await page.locator('[data-report-root]').waitFor();
 assert.equal(await page.getByRole('table',{name:'복습 문항 목록',exact:true}).locator('tbody tr').count(),10);
 const reviewNav=page.getByRole('navigation',{name:'복습 문항 페이지',exact:true});
 await reviewNav.getByRole('button',{name:'다음',exact:true}).click();
 const row=page.getByRole('table',{name:'복습 문항 목록',exact:true}).locator('tbody tr').first();
 const expectedDate=await row.locator('td').nth(0).innerText(),expectedNo=await row.locator('td').nth(1).innerText();
 await row.getByRole('button').click();
 await page.getByRole('tabpanel',{name:'문항 분석',exact:true}).waitFor();
 await page.waitForFunction(()=>document.activeElement?.id.startsWith('preview-item-'));
 assert.equal(await page.getByLabel('문항 시험일',{exact:true}).inputValue(),expectedDate);
 assert.ok((await page.locator(':focus').innerText()).includes(expectedNo.replace('번','')));
 assert.equal(await page.locator('[id^="preview-item-"]').count(),5);
 await page.getByRole('navigation',{name:'문항 분석 페이지',exact:true}).getByRole('button',{name:'이전',exact:true}).click();
 assert.equal(await page.locator('[id^="preview-item-"]').count(),20);
 await page.getByLabel('문항 필터',{exact:true}).selectOption('wrong');
 assert.equal(await page.locator('[id^="preview-item-"]').count(),5);
 await page.getByRole('tab',{name:'회차별 성적',exact:true}).click();
 assert.equal(await page.getByRole('table',{name:'회차별 성적 비교',exact:true}).locator('tbody tr').count(),10);
 const historyNav=page.getByRole('navigation',{name:'회차별 성적 페이지',exact:true});
 await historyNav.getByRole('button',{name:'다음',exact:true}).click();
 await historyNav.getByRole('button',{name:'다음',exact:true}).click();
 assert.equal(await page.getByRole('table',{name:'회차별 성적 비교',exact:true}).locator('tbody tr').count(),4);
 await page.screenshot({path:path.join(evidence,'volume-history.png'),fullPage:true});
 const popupEvent=page.waitForEvent('popup');await page.getByRole('button',{name:'선택 과목 A4 인쇄 / PDF 저장',exact:true}).click();const popup=await popupEvent;
 await popup.getByRole('button',{name:'인쇄 / PDF 저장',exact:true}).waitFor();
 assert.equal(await popup.locator('tbody[data-print-item]').count(),600);
 assert.equal(await popup.getByRole('table',{name:'회차별 성적 비교',exact:true}).locator('tbody tr').count(),24);
 assert.equal(await popup.getByRole('table',{name:'복습 문항 목록',exact:true}).locator('tbody tr').count(),120);
 await popup.close();
 assert.equal(await page.getByRole('table',{name:'회차별 성적 비교',exact:true}).locator('tbody tr').count(),4);
 await page.getByRole('tab',{name:'문항 분석',exact:true}).click();
 assert.equal(await page.getByLabel('문항 필터',{exact:true}).inputValue(),'wrong');
 assert.equal(await page.getByLabel('문항 시험일',{exact:true}).inputValue(),expectedDate);
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(evidence,'volume-results.json'),JSON.stringify({fixtureOnly:true,persisted:false,sessions:24,items:600,reviewItems:120,checks:['10-row review and history pages','20-item pages','cross-date review navigation and focus','filters clamp last page','all data in print and state restored'],errors},null,2));
 console.log('PASS 24 sessions / 600 items / 120 review items: pagination, review jump, filters, full print, restoration');
} finally {await browser.close();}
